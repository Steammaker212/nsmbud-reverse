// spawn_resources.cpp -- load the archives of whatever the level's actor
// spawners will create. See modbase/actor_spawner.h.
//
// =====================================================================
//  THE CRASH THIS FIXES (ledger F0223)
// =====================================================================
//
// Ryujinx 2026-10-26 07:05 and 07:09, identical both times, on the main thread:
//
//   Invalid memory access at virtual address 0x0
//   PC = main+0x430110  (0x60430110, inside ResArchive::getModel 0x604300DC)
//
//       604300dc  push {r4-r11, lr}       ; ResArchive::getModel(archive, name, ...)
//       ...
//       60430110  ldr  r0, [r4]           ; name->vtable
//       60430114  ldr  r6, [fp, #20]      ; archive->...   <- archive == null
//
// Level 1-1 (course1) places codedx's ActorSpawner (sprite 726) with
// event 1 -> sprite 724 (MrSun). MrSun's archive "mrsun" is a load-class-1
// archive (PROFILE_RESOURCES), and LoadProfileArchives (0x60008F10) loads
// class 1 only for the sprite ids in each area's *loaded-sprite list*
// (area->blocks[8], count at +0x9C; ledger F0202). The editor fills that list
// from the sprites it sees placed, so it holds 726 but never 724. When the
// event fires, MrSun asks ResArchiveMgr for "mrsun", gets null, and hands the
// null to getModel.
//
// So the spawner itself is fine; the actor it creates has no archive. Any
// spawner target with per-level archives crashes the same way.
//
// =====================================================================
//  THE FIX
// =====================================================================
//
// During the level load (mode 1), after the game loads the first profile, the
// placed-sprite block of every area (area->blocks[7], 0x18-byte records,
// count at +0x98) is scanned for actor spawners. Each one's target is decoded
// the way the spawner decodes it, and that profile's archives are loaded with
// the same call and the same "ActorResLoader" heap the game is using right
// then -- exactly what would have happened had the target been in the list.
//
// Record layout, from the area sprite builder sub_60005E40 (T1):
//
//   +0x00 u16 type          +0x08 u32 settings1     +0x12 u8 movementId
//   +0x02 u16 x             +0x0C u32 settings2     +0x13 u8 linkId
//   +0x04 u16 y             +0x11 u8  layer         +0x14 u8 initStateFlag
//   +0x06 u16 events (low byte eventId1, high byte eventId2)
//
// and the stride (add sl, sl, #24 at 0x60004B64).
//
// Deluxe (Switch) v1.0.0 only.

#include "modbase/actor_spawner.h"
#include "modbase/mod_archives.h"
#include "modbase/log.h"
#include "level/level.h"
#include "actors/profile.h"
#include "actors/profileid.h"

// Generated by sweet-dx from hooks/spawn_resources.hks.
namespace ModBase { namespace spawnerArchives { u32 loadArchives_orig(u32 mode, void* parentHeap); } }
namespace ModBase { namespace spawnerArchives { u32 loadResources_orig(Profile* profile, void* heap); } }

namespace {

constexpr u32 cLoadPerLevel = 1;    // LoadProfileArchives mode at level load
constexpr u32 cSpriteBlock  = 7;    // area->blocks[7]: placed sprites
constexpr u32 cMaxAreas     = 4;    // LoadProfileArchives walks areas 0-3

struct SpriteRecord
{
    u16 type;
    u16 x;
    u16 y;
    u16 events;
    u32 settings1;
    u32 settings2;
    u8  _10;
    u8  layer;
    u8  movementId;
    u8  linkId;
    u8  initStateFlag;
    u8  _15[3];
};
static_assert(sizeof(SpriteRecord) == 0x18, "area sprite record");

// Profiles that are actor spawners. codedx's is always there (the template
// code is required for custom profiles); mods add theirs.
u32 sSpawnerProfiles[ModBase::cMaxSpawnerProfiles] = { ProfileId::ActorSpawner };
u32 sNumSpawnerProfiles = 1;

bool sLevelLoad;    // inside LoadProfileArchives(mode 1)
bool sScanned;      // this load's spawners are already handled

bool isSpawner(u32 profileId)
{
    for (u32 i = 0; i < sNumSpawnerProfiles; i++)
        if (sSpawnerProfiles[i] == profileId)
            return true;
    return false;
}

void preloadSpawnTargets(void* heap)
{
    u32 loaded = 0;
    for (u32 a = 0; a < cMaxAreas; a++) {
        Level::Area* area = Level::instance ? Level::instance->getArea(a) : nullptr;
        if (!area || !area->blocks[cSpriteBlock])
            continue;
        const SpriteRecord* sprites = (const SpriteRecord*)area->blocks[cSpriteBlock];
        u32 count = area->blockEntryCounts[cSpriteBlock];
        for (u32 i = 0; i < count; i++) {
            const SpriteRecord& s = sprites[i];
            if (s.type == 0xFFFF)
                break;
            if (s.type >= ModBase::spriteTableSize()
                || !isSpawner(Profile::spriteToProfileList[s.type]))
                continue;

            u32 target = ModBase::spawnTarget(s.linkId, s.movementId);
            if (!target || target >= Profile::NUM_PROFILES || isSpawner(target))
                continue;
            Profile* profile = Profile::get(target);
            if (!profile || profile->hasResourcesLoaded)
                continue;
            ModBase::log("spawner: loading archives of profile ", target,
                         " for the spawner at area ", a, " sprite ", i);
            ModBase::spawnerArchives::loadResources_orig(profile, heap);
            loaded++;
        }
    }
    if (loaded)
        ModBase::log("spawner: ", loaded, " spawn target(s) loaded");
}

} // namespace

// LoadProfileArchives (0x60008F10): (mode, parent heap). Mode 1 is the level
// load; remember it so the per-profile hook knows which heap it is handed.
namespace ModBase { namespace spawnerArchives { u32 loadArchives(u32 mode, void* parentHeap); } }
u32 ModBase::spawnerArchives::loadArchives(u32 mode, void* parentHeap)
{
    // Before the first pass (game start): a mod archive missing from the SD
    // card is taken off the lists instead of crashing the loader (F0256).
    ModBase::dropMissingModArchives();
    bool prevLoad = sLevelLoad, prevScanned = sScanned;
    sLevelLoad = mode == cLoadPerLevel;
    sScanned = false;
    u32 r = ModBase::spawnerArchives::loadArchives_orig(mode, parentHeap);
    sLevelLoad = prevLoad;
    sScanned = prevScanned;
    return r;
}

// Profile_loadResources (0x60017FCC): (profile, heap). The first call of a
// level load is the earliest point the loader's own heap is known.
namespace ModBase { namespace spawnerArchives { u32 loadResources(Profile* profile, void* heap); } }
u32 ModBase::spawnerArchives::loadResources(Profile* profile, void* heap)
{
    u32 r = ModBase::spawnerArchives::loadResources_orig(profile, heap);
    if (sLevelLoad && !sScanned) {
        sScanned = true;
        preloadSpawnTargets(heap);
    }
    return r;
}

namespace {

// Load class 1 with no archives of its own: a level that lists the spawner
// then calls Profile_loadResources for it, which runs the scan above even in a
// level with no other per-level actor.
void makePerLevel(u32 profileId)
{
    if (profileId < Profile::NUM_PROFILES_ORIGINAL || profileId >= Profile::NUM_PROFILES)
        return;
    u32 custom = profileId - Profile::NUM_PROFILES_ORIGINAL;
    if (!Profile::resourceCountCustom[custom])
        Profile::hasResourcesCustom[custom] = cLoadPerLevel;
}

// codedx's spawner is in the table from the start (constant-initialised, so a
// mod registering from its own static constructor cannot run before it).
struct CodedxSpawnerClass
{
    CodedxSpawnerClass() { makePerLevel(ProfileId::ActorSpawner); }
} sCodedxSpawnerClass;

} // namespace

namespace ModBase {

void registerSpawnerProfile(u32 profileId)
{
    if (isSpawner(profileId) || sNumSpawnerProfiles >= cMaxSpawnerProfiles)
        return;
    sSpawnerProfiles[sNumSpawnerProfiles++] = profileId;
    makePerLevel(profileId);
}

} // namespace ModBase
