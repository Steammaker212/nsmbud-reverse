namespace {

const int cPlayerMode_PSquirrel = 8;    // Wii U PlayerMode; Deluxe tests +0x528 == 8 in 4 places

#if PACORN_USE_GAME_P_MODEL
// archiveTo = null: keep the archive, swap only the model inside it.
MODBASE_ACTOR_VARIANT(pAcornVariant,
    ProfileId::PAcorn, 598 /* Acorn */, "PAcorn", ModBase::cVariant_None,
    { { "I_musasabi", nullptr, "I_musasabi", "I_musasabiP" } });
#else
MODBASE_ACTOR_VARIANT(pAcornVariant,
    ProfileId::PAcorn, 598 /* Acorn */, "PAcorn", ModBase::cVariant_None,
    { { "I_musasabi", PACORN_ARCHIVE, "I_musasabi", PACORN_MODEL } });
#endif

struct PAcornInBlocks
{
    PAcornInBlocks()
    {
        ModBase::blockItems::registerContents(PACORN_BLOCK_CONTENTS, ProfileId::PAcorn);
    }
};
PAcornInBlocks pAcornInBlocks;

} // namespace

// The Acorn grant (0x604695B0): sub_60463998(item, &result, 7, 1), then the
// collect feedback. A P-Acorn asks for mode 8 instead.
namespace ModBase { namespace pAcorn { int acornGrant(void* item); } }
int ModBase::pAcorn::acornGrant(void* item)
{
    if (ModBase::variantProfileOf(item) != ProfileId::PAcorn)
        return ModBase::pAcorn::acornGrant_orig(item);

    int result = 0;
    if (((Item*)item)->grantMode(&result, cPlayerMode_PSquirrel, 1) != 1)
        return 0;
    u32 playerNo = *(u32*)((u8*)item + 0x1840);     // collector, set by the grant helper
    return ((Item*)item)->grantFeedback(result, playerNo);
}
