// p_acorn.cpp -- the P-Acorn from ?-blocks and bricks.
//
// The P-Acorn (player mode 8, Wii U cPlayerMode_PSquirrel) is a complete
// power-up in Deluxe, but no level item grants it: the only P-Acorn item
// model is used by the Quest/Challenge prize Toad hands out (profile 463).
// Every block item grants through sub_60463998(item, &result, mode, 1), and
// mode 8 is accepted like any other (sub_607A27A8 stores any mode; the mode
// table has 9 entries). So the P-Acorn here is the Acorn item (profile 598)
// whose grant asks for 8 instead of 7. Evidence: ledger F0044-F0048.
//
// =====================================================================
//  CONFIGURATION
// =====================================================================

// ?-blocks and bricks with this contents value hold a P-Acorn (one of the
// game's unused 21-31; the Hammer Flower uses 21). Small players get a
// Mushroom first, as from every Acorn block.
#define PACORN_BLOCK_CONTENTS   22

// 0: looks like the normal Acorn (always works).
// 1: try the game's own P-Acorn model, "I_musasabiP" (the Quest prize uses
//    it). It lives inside a game pack, so it is not added to the level's load
//    list; if it isn't loaded the normal Acorn model is used and the Ryujinx
//    log says "remap: archive 'I_musasabiP' is not loaded".
#define PACORN_USE_GAME_P_MODEL 1

// Or your own: romfs/Model/<archive>.Nin_NX_NVN.szs (set USE_GAME_P_MODEL 0).
// The Acorn item plays the same animations as the Fire Flower: out, out2,
// out3, wait, wait2 (inferred from the shared item class; check readable/).
#define PACORN_ARCHIVE          "I_musasabi"
#define PACORN_MODEL            "I_musasabi"

// =====================================================================

#include "profileid.h"
#include "nsmbudx/actor_variant.h"
#include "nsmbudx/block_items.h"

// symbols/p_acorn.sym
extern "C" int Item_grantMode(void* item, int* result, int mode, int contact);
extern "C" int Item_grantFeedback(void* item, int result, u32 playerNo);   // SE_PLY_GET_ITEM_AGAIN_ref

// Generated by sweet-dx from hooks/p_acorn.hks.
extern "C" int PAcorn_acornGrant_orig(void* item);

namespace {

const int cPlayerMode_PSquirrel = 8;    // Wii U PlayerMode; Deluxe tests +0x528 == 8 in 4 places

#if PACORN_USE_GAME_P_MODEL
NSMBUDX_ACTOR_VARIANT(pAcornVariant,
    ProfileId::PAcorn, 598 /* Acorn */, "PAcorn", nsmbudx::cVariant_NoArchiveLoad,
    { { "I_musasabi", "I_musasabiP", "I_musasabi", "I_musasabiP" } });
#else
NSMBUDX_ACTOR_VARIANT(pAcornVariant,
    ProfileId::PAcorn, 598 /* Acorn */, "PAcorn", nsmbudx::cVariant_None,
    { { "I_musasabi", PACORN_ARCHIVE, "I_musasabi", PACORN_MODEL } });
#endif

struct PAcornInBlocks
{
    PAcornInBlocks()
    {
        nsmbudx::blockItems::registerContents(PACORN_BLOCK_CONTENTS, ProfileId::PAcorn);
    }
};
PAcornInBlocks pAcornInBlocks;

} // namespace

// The Acorn grant (0x604695B0): sub_60463998(item, &result, 7, 1), then the
// collect feedback. A P-Acorn asks for mode 8 instead.
extern "C" int PAcorn_acornGrant(void* item)
{
    if (nsmbudx::variantProfileOf(item) != ProfileId::PAcorn)
        return PAcorn_acornGrant_orig(item);

    int result = 0;
    if (Item_grantMode(item, &result, cPlayerMode_PSquirrel, 1) != 1)
        return 0;
    u32 playerNo = *(u32*)((u8*)item + 0x1840);     // collector, set by the grant helper
    return Item_grantFeedback(item, result, playerNo);
}
