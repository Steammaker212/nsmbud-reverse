// hammer_suit.cpp -- a Hammer Flower power-up: its own item, throws hammers.
//
// =====================================================================
//  CONFIGURATION -- change these to use your own models.
//
//  An archive is romfs/Model/<archive>.Nin_NX_NVN.szs; a model is a model
//  name inside that archive. If a name you set cannot be found, the game
//  falls back to the vanilla one and logs a warning instead of crashing.
// =====================================================================

// The Hammer Flower item. The item code also plays skeletal animations named
// "out", "out2", "out3", "wait" and "wait2" from this archive, so a custom
// archive needs animations with those names.
#define HAMMER_ITEM_ARCHIVE         "I_fireflower"
#define HAMMER_ITEM_MODEL           "I_fireflower"

// The thrown hammer.
#define HAMMER_PROJECTILE_ARCHIVE   "bros"
#define HAMMER_PROJECTILE_MODEL     "bros_hammer"

// SMB3 allowed two hammers per player on screen.
#define HAMMER_MAX_PER_PLAYER       2

// 1: every Fire Flower also gives hammers (the v1 behaviour; handy for testing
// before a level contains a Hammer Flower). 0: only the Hammer Flower does.
#define HAMMER_FROM_ANY_FIRE_FLOWER 0

// ?-blocks and bricks whose contents is this value hold a Hammer Flower.
// Any of the game's unused values 21-31 (framework/items). Small players get
// a Mushroom first, like every other flower block.
#define HAMMER_BLOCK_CONTENTS       21

// The suit's colours: a frame of the player model's PB_switch / PH_switch /
// PC_switch texture-pattern animations (framework/player). 0 Normal, 1 Fire,
// 2 Ice. Add a 4th frame to those animations in your Mario/Luigi model
// archives and set this to 3.0f for a real Hammer Suit. Until then 2.0f
// borrows the Ice colours so the hammer thrower looks different. -1 = keep
// the Fire colours.
#define HAMMER_SUIT_FRAME           2.0f

// =====================================================================
//
// How it works. Every fact below is in data/findings/ledger.csv.
//
//  * The Hammer Flower is a new profile (ProfileId::HammerFlower, sprite
//    734, see profiles.txt) built by the game's own Fire Flower factory, so
//    it pops out, bounces and is collected exactly like a Fire Flower.
//  * Collecting it grants Fire mode (2) and marks that player as a hammer
//    thrower. Collecting a plain Fire Flower clears the mark, so plain Fire
//    Flowers throw fireballs again.
//  * The throw keeps the game's own animation and timing: only what
//    Player::createFireBall spawns is replaced. A hammer thrower gets the
//    Hammer Bros hammer (profile 759), created the way HammerBros_createHammer
//    does, with three per-instance changes (skip the held state, never pair
//    with players, attack as a Shell). Nothing shared is patched, so Hammer
//    Bros' own hammers still hurt Mario.
//  * Custom model names reach the game's own code through
//    nsmbudx::ScopedNameRemap, active only while the Hammer Flower's item
//    functions run or while our hammer is being created.
//
// Deluxe (Switch) v1.0.0 only.

