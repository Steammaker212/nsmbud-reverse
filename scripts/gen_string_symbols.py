"""Declare string-literal symbols (IDA `aFoo` names) that are used but never declared.

nsmbudx.sym carries them with addresses, e.g.
    aMCarrypWait  = 0x00AF9E00
    aMSjump2      = 0x00AFxxxx

but nsmbudx_undeclared.h only declares the ones an earlier pass happened to see referenced, so 177 names that
player.c and friends index into (`aMCarrypWait[v20]`) do not compile.

These are bytes in the read-only image, so they are declared as `extern const char <name>[]` at their recorded
address. The address comes from the symbol file; nothing is guessed. Only names that are actually used and
actually present in the .sym file are emitted.
"""
import os
import re

REPO = r"C:\Users\Saif Khan\Downloads\nsmbud-reverse"
ROOT = os.path.join(REPO, "decompiled")
INC = os.path.join(ROOT, "include")
OUT = os.path.join(INC, "nsmbudx_string_symbols.h")
SYM_PATH = os.path.join(REPO, "sweetdx", "symbols", "nsmbudx.sym")

USE = re.compile(r"(?<![.>])\b(a[A-Z][A-Za-z0-9_]{2,})\b")
SYM_LINE = re.compile(r"(\w+)\s*=\s*(0x[0-9A-Fa-f]+);")


def main():
    declared = set()
    for fn in sorted(os.listdir(INC)):
        if fn.endswith(".h") and fn != "nsmbudx_string_symbols.h":
            h = open(os.path.join(INC, fn), encoding="utf-8", errors="replace").read()
            declared |= set(re.findall(r"#define\s+(\w+)", h))
            declared |= set(re.findall(r"\bextern\b[^;\n]*?(\w+)\s*[;\[]", h))

    used = {}
    for dirpath, _, names in os.walk(ROOT):
        if "include" in dirpath or "authoritative" in dirpath:
            continue
        for fn in sorted(names):
            if not fn.endswith(".c"):
                continue
            t = open(os.path.join(dirpath, fn), encoding="utf-8", errors="replace").read()
            for m in USE.finditer(t):
                used.setdefault(m.group(1), 0)
                used[m.group(1)] += 1

    sym = open(SYM_PATH, encoding="utf-8", errors="replace").read()
    addrs = dict(SYM_LINE.findall(sym))

    lines = []
    unresolved = []
    for name in sorted(used):
        if name in declared:
            continue
        a = addrs.get(name)
        if a is None:
            unresolved.append(name)
            continue
        val = int(a, 16)
        if val < 0x60000000:
            val += 0x60000000
        lines.append("extern const char %-34s[];  /* 0x%08X */" % (name, val))

    header = (
        "/* String-literal symbols used by the corpus but never declared.\n"
        " *\n"
        " * Generated by scripts/gen_string_symbols.py -- do not edit by hand.\n"
        " *\n"
        " * nsmbudx.sym records these with addresses (e.g. aMCarrypWait = 0x00AF9E00), but the previous\n"
        " * header pass only declared those it happened to see, so 177 names that player.c indexes into did\n"
        " * not compile. Every address below is read from the symbol file; none is invented.\n"
        " */\n"
        "#ifndef NSMBUDX_STRING_SYMBOLS_H\n#define NSMBUDX_STRING_SYMBOLS_H\n\n"
    )
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(header + "\n".join(lines) + "\n\n#endif /* NSMBUDX_STRING_SYMBOLS_H */\n")

    print("undeclared string symbols: %d, declared from .sym: %d, unresolved: %d"
          % (len(used) - len(declared), len(lines), len(unresolved)))
    for nm in unresolved[:12]:
        print("   unresolved: %s" % nm)


if __name__ == "__main__":
    main()