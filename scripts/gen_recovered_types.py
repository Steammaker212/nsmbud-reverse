"""Declare the corpus-missing types that main.i64 has a size for, as sized opaque structs.

WHY THIS UNBLOCKS THINGS: the prototype comparison found 29 return-type disagreements that are real
improvements (`CollisionMgr *` where we say `int *`), and every attempt to adopt them failed with
"unknown type name" because this corpus has never declared CollisionMgr, StateBase, ActorBuildInfo,
StateExecuter, StateMethodExecuter and ~95 others. main.i64 stores no field names for those types, but it
does store their SIZE, and a sized opaque struct is enough to make the name legal and sizeof() correct:

    typedef struct CollisionMgr { uint8_t _opaque[0x14E8]; } CollisionMgr;

That is exactly the form this corpus already uses for CircularCollider and LightSource, so it matches
existing practice rather than inventing a new convention.

Skips any name that already appears as a typedef/struct/tag anywhere in the headers, so this can never
redeclare and conflict.
"""
import json
import os
import re
import sys

TYPES = r"C:\Users\Saif Khan\Downloads\main.idb\.rea\main_i64_types.json"

# names that are not C identifiers, or are IDA/toolchain bookkeeping rather than game types
SKIP_PAT = re.compile(r"^(\$|\d)|::")

# NEON/toolchain types are already defined in nsmbudx_types.h, some as unions and some as anonymous
# structs (`typedef struct { int32x4_t val[2]; } int32x4x2_t;`). A blacklist of scalar names caught the
# scalars but MISSED the x2/x3/x4 composite forms, which took the whole corpus to 0/475 with
# "typedef redefinition with different types". Enumerating is the wrong approach -- detect them by name
# SHAPE instead, since every NEON vector type ends in xN_t.
SKIP_NEON = re.compile(r"^(?:float|int|uint|poly)\d+x\d+(?:x\d+)?_t$|^__n(?:64|128)$")

# a hard backstop: anything the headers already define, whatever its spelling
DECL_PATTERNS = (
    r"typedef\s+struct\s+(\w+)",
    r"typedef\s+union\s+(\w+)",
    r"^\s*struct\s+(\w+)\s*[;{]",
    r"^\s*union\s+(\w+)\s*[;{]",
    r"typedef\s+\w+\s+(\w+)\s*;",          # typedef int foo;
    r"\}\s*(\w+)\s*;",                     # ... } foo;
)


def main(argv):
    headers = argv[1]
    out_name = argv[2] if len(argv) > 2 and not argv[2].startswith("--") else "nsmbudx_recovered_types.h"
    write = "--write" in argv

    with open(TYPES, encoding="utf-8") as fh:
        rows = [r for r in json.load(fh) if r["size"]]

    declared = set()
    for fn in os.listdir(headers):
        if not fn.endswith(".h"):
            continue
        # never read our own output back in: its `} Name;` lines would mark every type as declared
        if fn == out_name:
            continue
        with open(os.path.join(headers, fn), encoding="utf-8", errors="replace") as fh:
            t = fh.read()
        for _pat in DECL_PATTERNS:
            declared.update(re.findall(_pat, t, re.M))

    body = ["""/* Types recovered from main.i64 that this corpus had never declared.
 *
 * Generated by scripts/gen_recovered_types.py -- do not hand-edit.
 *
 * These are SIZED OPAQUE structs. main.i64 keeps no field names for them, so the only fact available per
 * type is its total size; declaring the name with that size makes `CollisionMgr *` a legal parameter
 * type and makes sizeof() correct, which is what the blocked prototype adoptions needed.
 *
 * Where a field layout is known from this corpus's own analysis, that struct lives elsewhere and this
 * generator skips it. Do not add fields here: put them in structs.h.
 *
 * Depends on uint8_t, so it includes the base types header itself; this keeps the file valid when
 * compiled standalone as well as from the prelude.
 */
#pragma once

#include "nsmbudx_types.h"
"""]
    added = []
    for r in sorted(rows, key=lambda x: x["name"]):
        nm = r["name"]
        if nm in declared or SKIP_NEON.match(nm) or SKIP_PAT.search(nm):
            continue
        size = int(r["size"], 0) if isinstance(r["size"], str) else r["size"]
        if size <= 0 or size > 0x100000:
            continue
        body.append("typedef struct %s { uint8_t _opaque[0x%X]; } %s;   /* sizeof 0x%X */"
                    % (nm, size, nm, size))
        added.append((nm, size))

    text = "\n".join(body) + "\n"
    path = os.path.join(headers, out_name)
    if write:
        with open(path, "w", encoding="utf-8", newline="") as fh:
            fh.write(text)
    print("types declared here : %d" % len(added))
    for nm, size in added[:30]:
        print("   %-40s 0x%X" % (nm, size))
    if len(added) > 30:
        print("   ... and %d more" % (len(added) - 30))
    print("\nwrote %s (write=%s)" % (path, write))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
