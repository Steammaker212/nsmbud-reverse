"""
export_named_functions.py
------------------------
Run inside IDA Pro (File > Script file...) with main.idb open.

Dumps a filtered JSON mapping of function addresses -> names, excluding
common autogenerated or unhelpful names (sub_, nullsub_, j_, loc_, thunk_).
This helps produce a curated function list as Script B described.
"""

import json
import idautils
import idc
import idaapi


def is_real_name(name):
    if not name:
        return False
    lower = name.lower()
    for p in ("sub_", "nullsub_", "j_", "loc_", "thunk_"):
        if lower.startswith(p):
            return False
    return True


def main():
    out = {}
    short_dn = idc.get_inf_attr(idc.INF_SHORT_DN)
    for ea in idautils.Functions():
        name = idc.get_func_name(ea)
        if not name:
            continue
        dem = idc.demangle_name(name, short_dn) if name else None
        readable = dem if dem else name
        if not is_real_name(readable):
            continue
        out[hex(ea)] = {
            "name": readable,
            "mangled": name if dem else None
        }

    path = "named_functions.json"
    with open(path, "w") as f:
        json.dump(out, f, indent=2, sort_keys=True)

    print("[*] Wrote %d named functions to %s" % (len(out), path))


if __name__ == "__main__":
    main()
