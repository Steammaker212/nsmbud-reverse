"""Extract struct/union fields from main.i64 and emit them as a C header.

Signature corrections found by probing (each of the first attempts failed on argument count):
    get_udm_by_tid(self, udm, tid)        returned -1 for index-style use; tid is a TYPE id, not a field
                                          index, so this is the wrong accessor for enumeration
    get_udm_by_offset(self, offset)       takes ONE argument (the byte offset), returns udm_t or None
    get_udt_details(self, udt)            needs an out-parameter `udtdata_t`
    get_udm(self, udm, index)             the indexed accessor that actually enumerates

Strategy: walk offsets using get_udm_by_offset, and if that yields nothing, fall back to get_udm with an
increasing index. Sizes come from get_size() and are trustworthy even when the body is opaque.
"""
import json
import os

import ida_typeinf
import idaapi

idaapi.auto_wait()

h_path = os.environ.get("NSMBUDX_H", r"C:\Users\Saif Khan\Downloads\main.idb\.rea\main_i64_types.h")
j_path = os.environ.get("NSMBUDX_OUT", r"C:\Users\Saif Khan\Downloads\main.idb\.rea\main_i64_types.json")

til = ida_typeinf.get_idati()
qty = ida_typeinf.get_ordinal_limit(til)

WANT = None          # set to a list of names to limit output
try:
    if os.environ.get("NSMBUDX_ONLY"):
        WANT = set(os.environ["NSMBUDX_ONLY"].split(","))
except Exception:                              # noqa: BLE001
    WANT = None


def type_text(tif):
    """A usable C spelling for a field's type."""
    for getter in ("dstr", "_print"):
        fn = getattr(tif, getter, None)
        if fn is None:
            continue
        try:
            s = fn()
            if s:
                return s.strip()
        except Exception:                      # noqa: BLE001
            pass
    name = ""
    try:
        name = tif.get_type_name() or ""
    except Exception:                          # noqa: BLE001
        pass
    return name or "int"


rows = []
lines = ["/* Struct/union layouts recovered from main.i64 (credited prior reverse-engineering work).",
         " * Generated by scripts/ida_export_main_i64_types.py -- do not hand-edit.",
         " */",
         "#pragma once",
         ""]

for ordinal in range(1, qty):
    tif = ida_typeinf.tinfo_t()
    if not tif.get_numbered_type(til, ordinal):
        continue
    name = tif.get_type_name() or ""
    if not name:
        continue
    is_struct = getattr(tif, "is_struct", lambda: False)()
    is_union = getattr(tif, "is_union", lambda: False)()
    is_enum = getattr(tif, "is_enum", lambda: False)()
    if not (is_struct or is_union or is_enum):
        continue
    if WANT and name not in WANT:
        continue
    try:
        size = tif.get_size()
    except Exception:                          # noqa: BLE001
        size = 0

    fields = []
    found_any = False
    # enumerate by index via get_udm, which is the indexed accessor in this build
    for i in range(0, 512):
        udm = ida_typeinf.udm_t()
        try:
            ok = tif.get_udm(udm, i)
        except Exception:                      # noqa: BLE001
            break
        if ok != 0 and ok is not True:
            break
        found_any = True
        try:
            fname = udm.name or ("f_%X" % (udm.offset // 8))
            ftype = type_text(udm.type)
            off = udm.offset // 8
            fsize = udm.size // 8
        except Exception:                      # noqa: BLE001
            break
        fields.append({"name": fname, "type": ftype, "offset": off, "size": fsize})

    rows.append({"ordinal": ordinal, "name": name, "size": size,
                 "kind": "union" if is_union else ("enum" if is_enum else "struct"),
                 "fields": fields})

    if fields:
        pad = max((f["offset"] for f in fields), default=0)
        lines.append("/* ordinal %d  size 0x%X  (at least 0x%X bytes of fields known) */" % (ordinal, size, pad))
        lines.append("%s %s {" % ("union" if is_union else "struct", name))
        for f in fields:
            lines.append("    /* +0x%03X  %2d bytes */ %s %s;" % (f["offset"], f["size"], f["type"], f["name"]))
        if size > pad + 4:
            lines.append("    /* +0x%03X .. 0x%X unaccounted */ uint8_t _pad_%X[0x%X];" % (pad + 4, size, pad + 4, size - pad - 4))
        lines.append("};")
        lines.append("")
    elif size:
        lines.append("/* ordinal %d  size 0x%X  OPAQUE: no field names stored in the database */" % (ordinal, size))
        lines.append("struct %s;" % name)
        lines.append("")

with open(h_path, "w", encoding="utf-8") as fh:
    fh.write("\n".join(lines))
with open(j_path, "w", encoding="utf-8") as fh:
    json.dump(rows, fh, indent=1)

with_fields = [r for r in rows if r["fields"]]
opaque = [r for r in rows if not r["fields"] and r["size"]]
print("types exported      : %d" % len(rows))
print("types with FIELDS   : %d" % len(with_fields))
print("opaque (size only)  : %d" % len(opaque))
for r in with_fields[:20]:
    print("   %-40s size=0x%-5X fields=%d" % (r["name"][:40], r["size"], len(r["fields"])))
print("opaque examples:")
for r in opaque[:12]:
    print("   %-40s size=0x%X" % (r["name"][:40], r["size"]))
print("header: %s" % h_path)
