"""Write struct headers whose members are the names the bodies actually use.

`recover_members.py` measures which member names each class's functions
dereference. This turns that evidence into C struct definitions so bodies that
use `actor->parent` compile.

Two rules keep the output honest:

* A member's offset is emitted only when it is known (a `field_XXXX` name from
  the recovered layout, or a `FIELD_U32(x, 0xNN)` access on the same base).
* A name with no known offset is placed in a trailing block of members and
  marked in a comment. The struct's byte layout is therefore *not* claimed to be
  faithful where the evidence is name-only; it is exactly as strong as the
  measurement, no stronger.

Usage:
    python gen_struct_headers.py --members <members.json> --out <dir>
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

# Members that exist on essentially every actor: mapping evidence only.
BASE_MEMBERS = {"vtable", "_", "heap", "id", "profile"}


def sanitize(name: str) -> str:
    return re.sub(r"\W", "_", name)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--members", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    data = json.loads(Path(args.members).read_text())
    classes: dict[str, dict[str, int]] = data.get("classes", {})

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    lines = [
        "/* nsmbudx_members.h -- struct members recovered from access patterns.",
        " *",
        " * Generated by scripts/pipeline/gen_struct_headers.py from the member",
        " * names the decompiled bodies dereference. A member named `field_XXXX`",
        " * carries a measured offset (hex); the others are name-only, listed after",
        " * a marker comment. Name-only members are not placed at a measured offset,",
        " * so a struct containing them does not claim a faithful byte layout.",
        " */",
        "#ifndef NSMBUDX_MEMBERS_H",
        "#define NSMBUDX_MEMBERS_H",
        "",
        '#include "nsmbudx_prelude.h"',
        "",
    ]

    written = 0
    for cls in sorted(classes):
        members = classes[cls]
        offsets = {}
        named = []
        for m, count in members.items():
            mo = re.match(r"field_([0-9A-Fa-f]+)$", m)
            if mo:
                offsets[int(mo.group(1), 16)] = m
            elif m not in BASE_MEMBERS:
                named.append((m, count))

        guard = "NSMBUDX_MEMBERS_%s" % sanitize(cls).upper()
        lines.append("#ifndef %s" % guard)
        lines.append("#define %s" % guard)
        lines.append(
            "/* %s: %d measured offsets, %d name-only members "
            "(observed %d times). */" % (cls, len(offsets), len(named),
                                          sum(members.values())))
        lines.append("typedef struct %s {" % sanitize(cls))
        prev = 0
        for off in sorted(offsets):
            if off > prev:
                lines.append("    unsigned char _pad_%X[%d];" % (prev, off - prev))
            lines.append("    unsigned int %s;" % offsets[off])
            prev = off + 4
        if named:
            lines.append("    /* name-only members: offset not established */")
            for m, _ in sorted(named):
                lines.append("    unsigned int %s;" % sanitize(m))
        if prev == 0 and not named:
            lines.append("    unsigned char _unknown[1];")
        lines.append("} %s;" % sanitize(cls))
        lines.append("#endif")
        lines.append("")
        written += 1

    lines.append("#endif /* NSMBUDX_MEMBERS_H */")
    (out / "nsmbudx_members.h").write_text("\n".join(lines))
    print("wrote %d struct definitions to %s" % (written, out / "nsmbudx_members.h"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
