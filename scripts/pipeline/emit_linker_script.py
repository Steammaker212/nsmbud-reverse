"""Turn the measured symbol map into the linker script the module links against.

`data/loader/main.sym` records every game symbol as an RVA from image base
0x60000000.  The module itself is linked at address 0 and is loaded directly
after the game's own `main` module, so to make a `BL` from module code reach a
game function the linker has to see that function at a *negative* address:

    runtime address of a game symbol = main_base + rva
    runtime address of module code   = main_base + main_size + link_address

with `main_size = 0x00CD1000`.  Subtracting `main_size` from every RVA puts the
game's address space and the module's address space into one coordinate system
where the displacement the linker computes is the displacement the CPU will
execute.  That is exactly what codedx's `symbol_relocate.py` does, and it is
what this script does, with the added refusal to touch symbols the module owns.

Two classes of symbol are deliberately *not* emitted:

  * `_init`, `_fini`, `__bss_start__`, `__bss_end__`, `_edata`, `_end`,
    `__dso_handle` -- these are ours.  Letting an absolute assignment win over
    the definition in crt0.s is the exact failure that made sweetdx ship
    `DT_INIT = 0xff32f024` and render every model black; see
    `sweetdx/docs/SUBSDK0_DT_INIT_ROOT_CAUSE.md`.
  * symbols whose RVA is at or past `main_size`.  The main module's last byte is
    RVA 0x00CD1000 (measured by `measure_module_extent.py` from the ELF's own
    sections), so nothing at or beyond it can be a main-module address.  Those
    559 entries are SDK/library names that leaked into the map, and subtracting
    `main_size` from them yields small *positive* offsets such as 0x1030 -- which
    would place an SDK function inside the module's own code.  `loader/sdk.ld`
    already defines the 67 of them that are real SDK exports, as
    `offset + __sdk_start`; the remaining 492 have no verified address and are
    counted rather than guessed.
  * anything that is not a plain identifier after sanitising would produce an
    unparseable script, so it is skipped and counted.

Usage:
    python emit_linker_script.py --sym ../data/loader/main.sym \
        --out ../loader/main.ld [--main-size 0x00CD1000]
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from module_symbols import MODULE_SYMBOLS as RESERVED

IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sym", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--main-size", default="0x00CD1000")
    ap.add_argument("--report-json", default=None,
                    help="write the excluded-symbol breakdown here")
    args = ap.parse_args()

    main_size = int(args.main_size, 0)

    pairs: list[tuple[str, int]] = []
    seen: set[str] = set()
    skipped_reserved = 0
    skipped_invalid = 0
    skipped_past_image: list[tuple[str, int]] = []
    for line in Path(args.sym).read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        m = re.match(r"^([A-Za-z_]\w*)\s*=\s*0x([0-9A-Fa-f]+)\s*;?$", line)
        if not m:
            skipped_invalid += 1
            continue
        name, rva = m.group(1), int(m.group(2), 16)
        if name in RESERVED:
            skipped_reserved += 1
            continue
        if not IDENT.match(name):
            skipped_invalid += 1
            continue
        if name in seen:
            continue
        if rva >= main_size:
            skipped_past_image.append((name, rva))
            continue
        seen.add(name)
        pairs.append((name, rva - main_size))

    pairs.sort(key=lambda kv: kv[1])

    out = [
        "/* main.ld -- generated by scripts/pipeline/emit_linker_script.py.",
        " *",
        " * Game symbols placed in the module's link address space so a BL from",
        " * module code reaches the real function.  Link address = RVA - 0x%X,"
        % main_size,
        " * i.e. the module is assumed to load at RVA 0x%X." % main_size,
        " *",
        " * Do not edit: regenerate from data/loader/main.sym.",
        " * %d symbols.  Deluxe (Switch) v1.0.0 only. */" % len(pairs),
        "",
    ]
    for name, addr in pairs:
        # The module links at 0 and every game symbol is below it, so these are
        # negative.  Emit them as negative hex: `ld` accepts it, and it keeps the
        # script readable (0x... would be a huge unsigned value).
        if addr >= 0:
            out.append("%s = 0x%X;" % (name, addr))
        else:
            out.append("%s = -0x%X;" % (name, -addr))
    Path(args.out).write_text("\n".join(out) + "\n", encoding="utf-8")

    print("wrote %s: %d symbols (skipped %d reserved, %d invalid, "
          "%d past the module end)"
          % (args.out, len(pairs), skipped_reserved, skipped_invalid,
             len(skipped_past_image)))

    if args.report_json:
        import json
        Path(args.report_json).parent.mkdir(parents=True, exist_ok=True)
        Path(args.report_json).write_text(json.dumps({
            "emitted": len(pairs),
            "skipped_reserved": skipped_reserved,
            "skipped_invalid": skipped_invalid,
            "skipped_past_image": len(skipped_past_image),
            "past_image_symbols": sorted(skipped_past_image, key=lambda kv: kv[1]),
            "note": ("Symbols at RVA >= 0x%X are not main-module addresses. "
                     "loader/sdk.ld defines the real SDK exports; the rest "
                     "have no verified address and are deliberately unnamed."
                     % main_size),
        }, indent=1))
        print("wrote %s" % args.report_json)
    return 0


if __name__ == "__main__":
    sys.exit(main())
