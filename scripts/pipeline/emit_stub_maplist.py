"""Emit the operator_delete veneer maplist and drop the stubs from the corpus.

Measured fact: 1,789 of the 1,793 `operator_delete_*` functions are 4 bytes and
all branch to the same address, 0x608DE3A0. They are PLT veneers, not distinct
functions. Keeping 1,793 filenames for 1,789 copies of one 4-byte `B` swamps the
corpus listing and tells a reader nothing.

This writes:

  data/loader/stub_maplist.txt   one line per veneer: RVA -> target, for scripts
  decompiled/src/stubs/operator_delete.maplist.c
                                 the single real implementation, plus the full
                                 address list as a comment block

and records which 4 outliers are *not* veneers so they are not silently dropped.
"""
from __future__ import annotations

import json
from pathlib import Path

WORK = Path(r"C:\Users\Saif Khan\Downloads\main.idb\_work")
REPO = Path(r"C:\Users\Saif Khan\Downloads\nsmbud-reverse")
ELF_BASE = 0x60000000


def main() -> int:
    stubs = json.loads((WORK / "stubs.json").read_text())
    cd = stubs["operator_delete"]
    target = cd["top_targets"][0]["target"]
    count = cd["top_targets"][0]["count"]
    print("operator_delete: %d stubs, %d branch to %s"
          % (cd["count"], count, target))

    veneers = [e for e in cd["entries"] if e["target"] == target]
    others = [e for e in cd["entries"] if e["target"] != target]
    print("  veneers: %d, non-veneers kept in corpus: %d"
          % (len(veneers), len(others)))

    # --- maplist for scripts
    out = REPO / "data" / "loader"
    out.mkdir(parents=True, exist_ok=True)
    lines = [
        "# operator_delete veneers, measured from the image.",
        "# Each line: <veneer RVA> <target RVA>. %d entries, all identical" % len(veneers),
        "# targets: every one is a 4-byte `B` to the shared implementation.",
        "# Generated by scripts/pipeline/collapse_stubs.py; do not edit.",
    ]
    for e in sorted(veneers, key=lambda x: int(x["ea"], 16)):
        rva = int(e["ea"], 16) - ELF_BASE
        trva = int(target, 16) - ELF_BASE
        lines.append("%08X %08X" % (rva, trva))
    (out / "stub_maplist.txt").write_text("\n".join(lines) + "\n")
    print("wrote %s (%d entries)" % (out / "stub_maplist.txt", len(veneers)))

    # --- the maplist C file
    stub_dir = REPO / "decompiled" / "src" / "stubs"
    stub_dir.mkdir(parents=True, exist_ok=True)
    impl_rva = int(target, 16) - ELF_BASE
    body = ["/* operator_delete veneers",
            " *",
            " * %d functions named operator_delete_* in the database are 4-byte" % len(veneers),
            " * veneers. Every one branches to the same implementation at",
            " * RVA 0x%08X, so they are recorded here once as a maplist instead of" % impl_rva,
            " * as %d separate translation units." % len(veneers),
            " *",
            " * Each line is <veneer RVA> <target RVA>; the full list is also in",
            " * data/loader/stub_maplist.txt.",
            " *",
            " * This is a Deluxe (Switch) finding: the veneer count and the shared",
            " * target were measured from this binary, not carried over from Wii U.",
            " */",
            "",
            "/* clang-format off */",
            "static const unsigned int operator_delete_veneer_target = 0x%08X;"
            % impl_rva,
            "static const unsigned int operator_delete_veneer_count = %d;" % len(veneers),
            "",
            "/* veneer RVA -> target RVA */",
            "static const unsigned int operator_delete_veneers[%d][2] = {"
            % len(veneers)]
    for e in sorted(veneers, key=lambda x: int(x["ea"], 16)):
        rva = int(e["ea"], 16) - ELF_BASE
        body.append("    { 0x%08X, 0x%08X }," % (rva, impl_rva))
    body.append("};")
    body.append("")
    if others:
        body.append("/* Not veneers: these have real bodies and stay in the corpus. */")
        for e in others:
            body.append("/*   0x%08X  size %d */"
                        % (int(e["ea"], 16) - ELF_BASE, e["size"]))
        body.append("")
    (stub_dir / "operator_delete_maplist.c").write_text("\n".join(body))
    print("wrote %s" % (stub_dir / "operator_delete_maplist.c"))

    # --- record the outliers so nothing is lost
    Path(WORK / "stub_outliers.json").write_text(json.dumps(others, indent=1))
    for e in others:
        print("  OUTLIER 0x%s size %d target %s"
              % (e["ea"][2:], e["size"], e["target"]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
