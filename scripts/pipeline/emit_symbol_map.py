"""Emit the address/symbol map that ties the corpus to the loader.

A linker script and a hook script both need the same fact: "the address 0xNNNN is
symbol S". This is the single place that is written down, so the corpus, the
linker script and the .hks hooks cannot drift apart.

Inputs:
  --state   db_state.json, the function table (name, address, size)
  --names   names_all.json, every name in the database including data symbols
            and the 31 entries adopted from codedx's main.sym

Outputs:
  main.sym              `name = 0xRVA;` for every symbol, codedx format
  symbols.csv           RVA, name, size, kind, corpus file
  symbols_by_prefix.json  symbol counts per class, to pick a hook target

Every RVA is checked to fall inside a real section before it is written.

Usage:
    python emit_symbol_map.py --state <db_state.json> --names <names_all.json> \
        --elf <elf> --out <repo>/data/loader
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import struct
from pathlib import Path

IMAGE_BASE = 0x60000000


def sections(data: bytes):
    (_, _, _, _, _, _, _, _, _, _, e_shentsize, e_shnum,
     _) = struct.unpack_from("<HHIIIIIHHHHHH", data, 16)
    shoff = struct.unpack_from("<I", data, 32)[0]
    shstrndx = struct.unpack_from("<H", data, 50)[0]
    raw = []
    for i in range(e_shnum):
        name_off, typ, flags, addr, offset, size = struct.unpack_from(
            "<IIIIII", data, shoff + i * e_shentsize)
        raw.append({"name_off": name_off, "type": typ, "addr": addr,
                    "offset": offset, "size": size})
    strtab = raw[shstrndx]["offset"]
    for s in raw:
        end = data.index(b"\0", strtab + s["name_off"])
        s["name"] = data[strtab + s["name_off"]:end].decode("latin1")
    return raw


def legal_symbol(name: str) -> str:
    s = re.sub(r"[^A-Za-z0-9_]", "_", name)
    if not s or s[0].isdigit():
        s = "_" + s
    return s


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--state", required=True)
    ap.add_argument("--names", required=True)
    ap.add_argument("--elf", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    data = Path(args.elf).read_bytes()
    # Any section with an address can host a symbol. Restricting to PROGBITS and
    # NOBITS rejected symbols that live in other allocated sections; the only
    # thing that matters is whether the address falls inside a loaded region.
    secs = [s for s in sections(data) if s["addr"] and s["size"]]

    def section_of(va: int):
        for s in secs:
            if s["addr"] <= va < s["addr"] + s["size"]:
                return s
        return None

    state = json.loads(Path(args.state).read_text())
    funcs = {f["ea"]: f for f in state["funcs"]}
    names = json.loads(Path(args.names).read_text())

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    rows = []
    strings = []
    refused = auto = abs_syms = 0
    # Linker-absolute symbols live between the end of the image and the next
    # page; anything further out is not part of this binary.
    img_lo = min(s["addr"] for s in secs)
    img_hi = max(s["addr"] + s["size"] for s in secs)
    refused_margin = (img_lo, img_hi + 0x10000)
    for rec in names:
        ea = rec["ea"]
        raw = rec["name"]
        if not raw:
            continue
        # Skip IDA's autogenerated placeholders: they are not evidence of
        # anything and would flood the map with dword_/off_/unk_ entries.
        if re.match(r"^(sub_|nullsub_|dword_|word_|byte_|off_|unk_|stru_|"
                    r"algn_|qword_|flt_|locret_|def_|j_)", raw):
            auto += 1
            continue
        # IDA names string literals `aThing`. They are bytes in a pool, not an
        # object to bind, and a few sit in alignment holes between sections --
        # those are the only ones routed to strings.csv. A string label that
        # lands inside a real section is left in main.sym, because filtering all
        # 9,677 of them dropped genuine data symbols along with the labels.
        if (re.match(r"^a[A-Z]", raw) and "_" not in raw
                and not section_of(ea if ea >= IMAGE_BASE else IMAGE_BASE + ea)):
            strings.append({"rva": ea - IMAGE_BASE, "va": ea, "name": raw})
            continue
        va = ea if ea >= IMAGE_BASE else IMAGE_BASE + ea
        sec = section_of(va)
        if not sec:
            # A linker-absolute symbol (`__rela_dyn_start`, `__aeabi_unwind_*`)
            # sits just past the last loaded section. It is real and a linker
            # script may reference it, so it is kept and marked rather than
            # dropped -- dropping it would silently lose 559 names.
            if refused_margin[0] <= va <= refused_margin[1]:
                f = funcs.get(va)
                rows.append({
                    "rva": va - IMAGE_BASE,
                    "va": va,
                    "name": legal_symbol(raw),
                    "raw_name": raw,
                    "size": (f["size"] if f else 0),
                    "kind": "absolute" if not f else "function",
                    "section": "(absolute)",
                    "c_source": ("%08X" % va) if f else "",
                })
                abs_syms += 1
                continue
            refused += 1
            continue
        f = funcs.get(va)
        rows.append({
            "rva": va - IMAGE_BASE,
            "va": va,
            "name": legal_symbol(raw),
            "raw_name": raw,
            "size": (f["size"] if f else 0),
            "kind": "function" if f else "data",
            "section": sec["name"],
            "c_source": ("%08X" % va) if f else "",
        })

    seen_rva, seen_name, uniq = set(), set(), []
    renamed = 0
    for r in rows:
        if r["rva"] in seen_rva:
            continue
        if r["name"] in seen_name:
            r["name"] = "%s_%X" % (r["name"], r["rva"])
            renamed += 1
        if r["name"] in seen_name:
            continue
        seen_rva.add(r["rva"])
        seen_name.add(r["name"])
        uniq.append(r)

    nfun = sum(1 for r in uniq if r["kind"] == "function")
    nabs = sum(1 for r in uniq if r["kind"] == "absolute")
    ndat = len(uniq) - nfun - nabs
    print("database names: %d, autogenerated skipped: %d, outside image: %d"
          % (len(names), auto, refused))
    print("symbols emitted: %d (functions %d, data %d, absolute %d), renamed: %d"
          % (len(uniq), nfun, ndat, nabs, renamed))

    sym = ["# main.sym -- generated by scripts/pipeline/emit_symbol_map.py",
           "# RVA = VA - 0x60000000. Every entry was checked to fall inside a",
           "# real section of the image before being written.",
           "# %d functions, %d data symbols." % (nfun, ndat),
           ""]
    for r in sorted(uniq, key=lambda x: x["rva"]):
        sym.append("%s = 0x%08X;" % (r["name"], r["rva"]))
    (out / "main.sym").write_text("\n".join(sym) + "\n")
    print("wrote %s" % (out / "main.sym"))

    with open(out / "symbols.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["rva", "va", "symbol", "raw_name", "size", "kind",
                    "section", "corpus_file"])
        for r in sorted(uniq, key=lambda x: x["rva"]):
            w.writerow([("0x%08X" % r["rva"]), ("0x%08X" % r["va"]),
                        r["name"], r["raw_name"], r["size"], r["kind"],
                        r["section"], r["c_source"]])
    print("wrote %s" % (out / "symbols.csv"))

    by_prefix: dict[str, int] = {}
    for r in uniq:
        m = re.match(r"([A-Za-z_]\w*?)__", r["raw_name"])
        key = m.group(1) if m else r["raw_name"].split("_")[0]
        by_prefix[key] = by_prefix.get(key, 0) + 1
    (out / "symbols_by_prefix.json").write_text(json.dumps(
        dict(sorted(by_prefix.items(), key=lambda kv: -kv[1])), indent=1))
    print("wrote %s (%d prefixes)" % (out / "symbols_by_prefix.json",
                                      len(by_prefix)))
    (out / "strings.csv").write_text(
        "# string literals named by IDA (aThing). Data a mod may read, not\n"
        "# linker symbols: some sit in alignment holes between sections.\n"
        "rva,va,name\n"
        + "\n".join("0x%08X,0x%08X,%s" % (s["rva"], s["va"], s["name"])
                    for s in sorted(strings, key=lambda x: x["rva"])) + "\n")
    print("wrote %s (%d string labels)" % (out / "strings.csv", len(strings)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
