"""Measure the per-function corpus and build its undeclared-symbol header.

Compiles each emitted function file independently, aggregates the diagnostics,
and writes ``nsmbudx_undeclared.h`` covering every symbol the bodies reference
but do not declare. Iterating this to a fixed point is what makes the corpus
parse as a whole.

Usage:
    python measure_per_function.py --dir <per_fn> [--rounds 3]
"""
from __future__ import annotations

import argparse
import collections
import json
import re
import subprocess
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ERR_RE = re.compile(r"error: (.*)")
UNDECL_RE = re.compile(r"undeclared identifier '([A-Za-z_]\w*)'")
IMPLICIT_RE = re.compile(r"undeclared function '([A-Za-z_]\w*)'")

RESERVED = {
    "vsnprintf", "snprintf", "printf", "sprintf", "vprintf", "sscanf", "strstr",
    "strlen", "strcpy", "strncpy", "strcmp", "strncmp", "strchr", "strrchr",
    "strcat", "memcpy", "memmove", "memset", "memcmp", "atanf", "atan", "atan2",
    "sinf", "cosf", "tanf", "sqrtf", "sqrt", "fabs", "fabsf", "exp", "expf",
    "pow", "powf", "log", "logf", "floor", "floorf", "ceil", "ceilf", "strtod",
    "strtol", "malloc", "calloc", "realloc", "free", "abort", "exit",
}


def run_unit(u: Path, inc: Path) -> tuple[list[str], set[str], set[str]]:
    p = subprocess.run(
        ["clang", "-fsyntax-only", "-std=gnu89", "-Wno-everything",
         "-ferror-limit=0", "-I", str(inc), str(u)],
        capture_output=True, text=True,
    )
    return (ERR_RE.findall(p.stderr),
            set(UNDECL_RE.findall(p.stderr)),
            set(IMPLICIT_RE.findall(p.stderr)))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", required=True)
    ap.add_argument("--jobs", type=int, default=12)
    ap.add_argument("--rounds", type=int, default=3)
    args = ap.parse_args()

    d = Path(args.dir)
    inc = d / "include"
    units = sorted(p for p in d.glob("*/*.c") if p.name != "g_image.c")
    print("units: %d" % len(units))

    data: set[str] = set()
    funcs: set[str] = set()
    header = inc / "nsmbudx_undeclared.h"

    for rnd in range(args.rounds):
        with ThreadPoolExecutor(max_workers=args.jobs) as pool:
            results = list(pool.map(lambda u: run_unit(u, inc), units))
        errs: list[str] = []
        u_data: set[str] = set()
        u_funcs: set[str] = set()
        for e, ud, uf in results:
            errs += e
            u_data |= ud
            u_funcs |= uf

        u_funcs |= {n for n in u_data if n.startswith(("sub_", "nullsub_", "j_"))}
        u_data -= u_funcs
        u_data -= RESERVED
        data |= u_data
        funcs |= u_funcs

        kinds = collections.Counter(re.sub(r"'[^']*'", "'X'", e) for e in errs)
        clean = sum(1 for e, _, _ in results if not e)
        print("round %d: clean %d/%d  errors %d  undeclared %d/%d"
              % (rnd + 1, clean, len(units), len(errs), len(u_data), len(u_funcs)))

        # Globals assigned directly are scalars, not arrays.
        body = "\n".join(p.read_text(encoding="utf-8", errors="replace") for p in units[:2000])
        assigned = {n for n in data if re.search(r"(?<![\w.>])%s\s*=(?!=)" % re.escape(n), body)}

        lines = [
            "/* nsmbudx_undeclared.h -- symbols the corpus references.",
            " *",
            " * Generated by scripts/pipeline/measure_per_function.py from the",
            " * compiler's own diagnostics. Every name here is one a decompiled body",
            " * actually uses. Assigned globals are scalars; the rest are arrays.",
            " * Widths are not asserted.",
            " */",
            "#ifndef NSMBUDX_UNDECLARED_H",
            "#define NSMBUDX_UNDECLARED_H",
            "",
            '#include "nsmbudx_prelude.h"',
            "",
        ]
        for n in sorted(data - assigned):
            lines.append("extern unsigned char %s[];" % n)
        for n in sorted(data & assigned):
            lines.append("extern uintptr_t %s;" % n)
        for n in sorted(funcs):
            lines.append("int %s();" % n)
        lines += ["", "#endif"]
        header.write_text("\n".join(lines), encoding="utf-8")

        try:
            (d / "diagnostics.json").write_text(json.dumps(dict(kinds.most_common(40)), indent=1))
        except Exception:
            pass
        if not errs:
            print("clean at round %d" % (rnd + 1))
            break

    print("declared data %d functions %d" % (len(data), len(funcs)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
