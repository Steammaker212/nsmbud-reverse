"""Split verified hook sites from the hooks that can actually be built.

gen_hooks.py finds 80 sites where a real B/BL targets a named function. That is a
catalogue of *opportunities*, not a build.

A .hks file is a build instruction: every `func:` it names must have a definition
or the link fails with an undefined symbol. So this filters the catalogue down to
the hooks that have C, and writes two files:

  hooks/candidate_hooks.hks   all verified sites, for choosing a target
  hooks/hooks.hks             only those with a definition in loader/hooks/*.c

Emitting a forwarder for the rest would be easy and wrong: a forwarder needs the
function's true prototype, and getting the arity wrong corrupts registers at
runtime. A hook is only listed when someone wrote it against the real signature.

Usage:
    python select_hooks.py --repo <repo>
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True)
    ap.add_argument("--candidates", default="candidate_hooks.json")
    args = ap.parse_args()

    repo = Path(args.repo)
    hooks_dir = repo / "hooks"
    src_dir = repo / "loader" / "hooks"

    cand = json.loads((hooks_dir / args.candidates).read_text())

    # Every function a .c file in loader/hooks/ actually defines.
    defined: set[str] = set()
    for p in sorted(src_dir.glob("*.c")) if src_dir.exists() else []:
        txt = p.read_text(encoding="utf-8", errors="replace")
        for m in re.finditer(r"^[A-Za-z_][\w \t\*]*?\b(\w+)\s*\([^;{]*\)\s*\{",
                             txt, re.M):
            defined.add(m.group(1))
    print("functions defined in loader/hooks/: %d" % len(defined))

    buildable = [h for h in cand if h["func"] in defined]
    print("verified sites: %d, buildable hooks: %d" % (len(cand), len(buildable)))

    def render(items, title, note):
        out = ["# %s" % title, "#", "# Generated by scripts/pipeline/gen_hooks.py.",
               "# Every site below was found by decoding a real B/BL in .text and",
               "# confirming its displacement lands on the named symbol.",
               "#", "# Deluxe (Switch) v1.0.0 only. RVAs are relative to 0x60000000.",
               "#"]
        for line in note:
            out.append("# %s" % line)
        out.append("")
        for h in items:
            out.append("%s:" % h["hook"])
            out.append("    type:   %s" % h["type"])
            out.append("    func:   %s" % h["func"])
            out.append("    addr:   0x%08X" % h["site_rva"])
            out.append("    # -> %s (0x%08X), %d caller(s)"
                       % (h["target_name"], h["target_rva"], h["callers"]))
            out.append("")
        return "\n".join(out)

    (hooks_dir / "candidate_hooks.hks").write_text(render(
        cand, "candidate hook sites",
        ["This is a catalogue, not a build. Wire one into hooks.hks by writing",
         "its C in loader/hooks/ and re-running select_hooks.py."]))
    print("wrote hooks/candidate_hooks.hks (%d sites)" % len(cand))

    (hooks_dir / "hooks.hks").write_text(render(
        buildable, "active hooks",
        ["Only hooks with a C definition appear here, so this file links.",
         "See candidate_hooks.hks for the full verified catalogue."]))
    print("wrote hooks/hooks.hks (%d hooks)" % len(buildable))

    for h in buildable:
        print("  ACTIVE 0x%08X %-10s -> %s"
              % (h["site_rva"], h["type"], h["target_name"]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
