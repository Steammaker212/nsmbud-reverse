"""Regenerate the hook table inside docs/LOADER_STATUS.md from hooks/hooks.hks.

A hand-maintained table drifts from the build the first time a hook is added or
retired. This rewrites only the region between the two marker comments, so the
surrounding prose stays hand-written.

Usage:
    python scripts/pipeline/render_status_hooks.py --repo .            # print
    python scripts/pipeline/render_status_hooks.py --repo . --write    # update doc
"""
from __future__ import annotations

import argparse
import io
import re
from pathlib import Path

BEGIN = "<!-- BEGIN HOOK TABLE (generated by render_status_hooks.py) -->"
END = "<!-- END HOOK TABLE -->"


def parse(path: Path):
    """[(site_rva, hook_name, type, target_name, callers)] in site order."""
    text = io.open(path, encoding="utf-8", errors="replace").read()
    rows = []
    for blk in re.split(r"\n(?=[A-Za-z_]\w*:)", text):
        m = re.match(r"^([A-Za-z_]\w*):", blk)
        if not m:
            continue
        name = m.group(1)
        a = re.search(r"addr:\s*(0x[0-9A-Fa-f]+)", blk)
        t = re.search(r"type:\s*(\w+)", blk)
        # "    @ -> Target (0x008138), 323 caller(s)"
        # "    @ -> static_init_hook (module) (0x0000019C), 1 caller(s)"
        tg = re.search(r"@\s*->\s*(\S+?)\s*(?:\(module\)\s*)?\(0x([0-9A-Fa-f]+)\)", blk)
        c = re.search(r",\s*(\d+)\s*caller", blk)
        if not a:
            continue
        rows.append((int(a.group(1), 16), name, t.group(1) if t else "?",
                     tg.group(1) if tg else "?", c.group(1) if c else "?"))
    rows.sort()
    return rows


def render(rows) -> list[str]:
    out = [BEGIN, "",
           "| Site RVA | Target | Branch | Callers |",
           "| --- | --- | --- | ---: |"]
    for rva, name, typ, target, callers in rows:
        if target == "static_init_hook":
            out.append("| 0x%06X | `static_init_hook` (mandatory) | %s | — |"
                       % (rva, typ))
        else:
            out.append("| 0x%06X | `%s` | %s | %s |" % (rva, target, typ, callers))
    out.append("")
    out.append(END)
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True)
    ap.add_argument("--write", action="store_true")
    opt = ap.parse_args()

    repo = Path(opt.repo)
    rows = parse(repo / "hooks" / "hooks.hks")
    block = render(rows)

    doc = repo / "docs" / "LOADER_STATUS.md"
    text = io.open(doc, encoding="utf-8").read()
    if BEGIN in text and END in text:
        pre = text[: text.index(BEGIN)]
        post = text[text.index(END) + len(END):]
        new = pre + "\n".join(block) + post
    else:
        # Insert after the paragraph that introduces the table.
        anchor = "attribute."
        idx = text.index(anchor) + len(anchor)
        new = text[:idx] + "\n\n" + "\n".join(block) + text[idx:]

    if opt.write:
        io.open(doc, "w", encoding="utf-8", newline="\n").write(new)
        print("updated %s (%d hooks)" % (doc, len(rows)))
    else:
        print("\n".join(block))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
